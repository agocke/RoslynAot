using Microsoft.CodeAnalysis;

namespace RoslynAot.RoslynFacadeGenerator;

/// <param name="Reason">Why the type cannot be remoted.</param>
/// <param name="DefaultVisitWalksChildren">
/// Whether the type's <c>DefaultVisit</c> descends into an operation's
/// children, which is the whole difference between a visitor and a walker.
/// </param>
internal sealed record LocalVisitorEntry(
    string Reason,
    bool DefaultVisitWalksChildren);

/// <summary>
/// Visitor base classes the analyzer constructs and the compiler never hands
/// over, so their dispatch has to happen analyzer-side.
/// </summary>
/// <remarks>
/// These are declared rather than derived because "the analyzer subclasses
/// this and calls it on compiler-owned objects" is not a shape the projection
/// can read off a type. Deriving ownership gave them <c>Remote</c>, which is
/// how <c>CA1845</c> came to fail with "this Roslyn facade value has no
/// control vtbl": <c>UseSpanBasedStringConcat</c> news up its own walker, so
/// there is no handle behind it and every remoted member throws on a null
/// vtbl. That is not a missing member — the member exists and is projected —
/// which is why it read as a different failure class from everything else in
/// the burn-down.
///
/// The bodies are generated by rule rather than declared per member, because
/// <c>OperationVisitor</c> has 129 <c>VisitXxx</c> overloads and a table of
/// 129 identical entries would be a worse record of the decision than one
/// rule. The rule is exactly Roslyn's own shape:
/// <list type="bullet">
/// <item><c>Visit</c> dispatches on the operation's runtime type to the
/// matching <c>VisitXxx</c>, so an analyzer's override wins.</item>
/// <item><c>VisitXxx</c> falls through to <c>DefaultVisit</c>.</item>
/// <item><c>DefaultVisit</c> does nothing, or walks children.</item>
/// </list>
/// Every part of that is derivable from public API: each <c>VisitXxx</c>
/// method's single parameter names the interface to dispatch on, and
/// <c>IOperation.ChildOperations</c> gives the walk. No name matching, and no
/// dependence on <c>OperationKind</c> — whose mapping to interfaces is
/// irregular enough (<c>Increment</c> and <c>Decrement</c> share
/// <c>IIncrementOrDecrementOperation</c>) that deriving it would need a table
/// of exceptions.
/// </remarks>
internal static class ProjectionLocalVisitors
{
    private static readonly IReadOnlyDictionary<string, LocalVisitorEntry>
        s_entries = new Dictionary<string, LocalVisitorEntry>(
            StringComparer.Ordinal)
    {
        ["[Microsoft.CodeAnalysis]T:Microsoft.CodeAnalysis.Operations.OperationVisitor"] = new(
            "An analyzer subclasses it and calls Visit on compiler-owned " +
            "operations. The compiler never constructs one, so there is no " +
            "handle for a remoted member to dispatch on.",
            DefaultVisitWalksChildren: false),

        ["[Microsoft.CodeAnalysis]T:Microsoft.CodeAnalysis.Operations.OperationWalker"] = new(
            "As OperationVisitor, and its DefaultVisit descends into an " +
            "operation's children, which is the only thing that makes it a " +
            "walker.",
            DefaultVisitWalksChildren: true),
    };

    public static IEnumerable<string> Ids => s_entries.Keys;

    public static bool TryGet(
        string canonicalId,
        out LocalVisitorEntry entry) =>
        s_entries.TryGetValue(canonicalId, out entry!);

    public static bool IsLocalVisitor(INamedTypeSymbol type) =>
        TryGet(
            CanonicalSignatureBuilder.GetCanonicalId(type),
            out _);

    /// <summary>
    /// The analyzer-side body for one member of a declared visitor, or false
    /// if the member is not one of the three shapes the rule covers.
    /// </summary>
    public static bool TryGetStatements(
        ProjectedCall call,
        ProjectionModel model,
        out IReadOnlyList<string> statements)
    {
        statements = [];
        IMethodSymbol method = call.Symbol;
        if (!TryGet(
                CanonicalSignatureBuilder.GetCanonicalId(
                    method.ContainingType),
                out LocalVisitorEntry entry) ||
            method.Parameters is not [IParameterSymbol parameter])
        {
            return false;
        }

        string name = CSharpName.EscapeIdentifier(parameter.Name);
        switch (method.Name)
        {
            case "Visit":
                // A walker's Visit overrides a visitor's and dispatches
                // identically. Emitting the switch again would duplicate 129
                // cases per subclass for no behavioural difference, so the
                // override defers and the table is generated once.
                statements = OverridesLocalVisitor(method)
                    ? [$"base.Visit({name});"]
                    : GetDispatchStatements(
                        method.ContainingType,
                        name,
                        model);
                return true;

            case "DefaultVisit":
                // ImmutableArray, not the OperationList enumerator: the
                // enumerator's MoveNext and Current are not projected, so
                // foreach over the list itself would throw on the first
                // child.
                statements = entry.DefaultVisitWalksChildren
                    ?
                    [
                        $"foreach (var __roslynAotChild in {name}." +
                        "ChildOperations.ToImmutableArray()) " +
                        "Visit(__roslynAotChild);",
                    ]
                    : [];
                return true;

            default:
                // Every other single-parameter Visit overload is a leaf that
                // Roslyn defines as falling through to DefaultVisit.
                if (!method.Name.StartsWith("Visit", StringComparison.Ordinal))
                {
                    return false;
                }

                statements = [$"DefaultVisit({name});"];
                return true;
        }
    }

    private static bool OverridesLocalVisitor(IMethodSymbol method) =>
        method.IsOverride &&
        method.OverriddenMethod is { } overridden &&
        TryGet(
            CanonicalSignatureBuilder.GetCanonicalId(
                overridden.ContainingType),
            out _);

    /// <summary>
    /// One crossing to learn the operation's most-derived projected interface,
    /// then a switch to the matching overload.
    /// </summary>
    /// <remarks>
    /// The alternative — testing <c>is IXxxOperation</c> against each
    /// candidate in turn — is a crossing per candidate, and there are 129 of
    /// them, on every node of every walk.
    /// </remarks>
    private static IReadOnlyList<string> GetDispatchStatements(
        INamedTypeSymbol visitorType,
        string parameterName,
        ProjectionModel model)
    {
        var statements = new List<string>
        {
            $"if ({parameterName} is null) return;",
            "global::RoslynAot.Abi.IRoslynControlVtbl __roslynAotControl = " +
            $"{parameterName}.__RoslynAotGetControlVtbl();",
            "int __roslynAotStatus = __roslynAotControl" +
            ".GetObjectRuntimeVtblId(" +
            $"{parameterName}.__RoslynAotGetHandle(__roslynAotControl), " +
            "out long __roslynAotLow, out long __roslynAotHigh);",
            "global::RoslynAot.RoslynFacade.RoslynFacadeRuntime" +
            ".ThrowIfFailed(__roslynAotControl, __roslynAotStatus);",
            "switch ((__roslynAotLow, __roslynAotHigh))",
            "{",
        };

        foreach ((IMethodSymbol method, INamedTypeSymbol operationType) in
            GetVisitOverloads(visitorType))
        {
            if (!model.TryGetInstanceVtblId(
                    operationType,
                    out long low,
                    out long high))
            {
                continue;
            }

            string operationTypeName = operationType.ToDisplayString(
                SymbolDisplayFormat.FullyQualifiedFormat);
            statements.Add(
                $"    case ({low}L, {high}L): " +
                $"{CSharpName.EscapeIdentifier(method.Name)}(" +
                $"({operationTypeName}){parameterName}); return;");
        }

        statements.Add($"    default: DefaultVisit({parameterName}); return;");
        statements.Add("}");
        return statements;
    }

    /// <summary>
    /// The visitor's leaf overloads, paired with the interface each dispatches
    /// on. Ordering is by the interface's metadata name so the generated
    /// switch is stable across runs.
    /// </summary>
    private static IEnumerable<(IMethodSymbol Method, INamedTypeSymbol Operation)>
        GetVisitOverloads(INamedTypeSymbol visitorType) =>
        visitorType.GetMembers()
            .OfType<IMethodSymbol>()
            .Where(method =>
                method.MethodKind == MethodKind.Ordinary &&
                method.Name.StartsWith("Visit", StringComparison.Ordinal) &&
                method.Name is not "Visit" &&
                method.DeclaredAccessibility is
                    Accessibility.Public or Accessibility.Protected &&
                method.Parameters is
                    [{ Type: INamedTypeSymbol { TypeKind: TypeKind.Interface } }])
            .Select(method => (
                Method: method,
                Operation: (INamedTypeSymbol)method.Parameters[0].Type))
            .OrderBy(
                pair => CanonicalSignatureBuilder.GetMetadataTypeName(
                    pair.Operation),
                StringComparer.Ordinal);
}
